/* Mentor-only profile preview and archived mentorship controls. */
(() => {
  'use strict';
  const detailsModal = document.getElementById('mentorMenteeDetailsModal');
  const detailContent = document.getElementById('mentorMenteeDetailsContent');
  const detailsTitle = document.getElementById('mentorMenteeDetailsTitle');
  const endModal = document.getElementById('mentorEndMentorshipModal');
  const endForm = document.getElementById('mentorEndMentorshipForm');
  if (!detailsModal || !endModal) return;

  // Bootstrap only opens when invoked from a trusted user event.
  document.addEventListener('click', event => {
    const detailTrigger = event.target.closest('[data-mentee-details-url]');
    if (detailTrigger) bootstrap.Modal.getOrCreateInstance(detailsModal).show(detailTrigger);
    const endTrigger = event.target.closest('[data-end-mentorship-url]');
    if (endTrigger) bootstrap.Modal.getOrCreateInstance(endModal).show(endTrigger);
  });

  let latestRequest = 0;
  detailsModal.addEventListener('show.bs.modal', async event => {
    const trigger = event.relatedTarget;
    if (!trigger?.dataset.menteeDetailsUrl) return;
    const requestId = ++latestRequest;
    detailsTitle.textContent = `${trigger.dataset.menteeDetailsName || 'Mentee'} · Details`;
    detailContent.textContent = 'Loading mentee details…';
    try {
      const response = await fetch(trigger.dataset.menteeDetailsUrl, {
        credentials: 'same-origin', headers: {'Accept': 'text/html'}
      });
      if (!response.ok || response.redirected) throw new Error('Profile details are unavailable. Refresh your session and try again.');
      const html = await response.text();
      if (requestId !== latestRequest) return;
      detailContent.innerHTML = html; // HTML generated by the authorized Django template, not user input.
    } catch (error) {
      if (requestId !== latestRequest) return;
      detailContent.textContent = error.message;
      detailContent.setAttribute('role', 'alert');
    }
  });
  detailsModal.addEventListener('hidden.bs.modal', () => {latestRequest++;detailContent.removeAttribute('role');});

  const endName = document.getElementById('mentorEndMentorshipDescription');
  const endError = document.getElementById('mentorEndMentorshipError');
  endModal.addEventListener('show.bs.modal', event => {
    const trigger = event.relatedTarget;
    if (!trigger) return;
    endForm.dataset.submitUrl = trigger.dataset.endMentorshipUrl || '';
    endForm.reset();
    endName.textContent = `End your active mentorship with ${trigger.dataset.endMentorshipName || 'this mentee'}? This will revoke access to your mentoring group while preserving previous records.`;
    endError.hidden = true;
    endError.textContent = '';
  });
  endForm.addEventListener('submit', async event => {
    event.preventDefault();
    if (!endForm.reportValidity() || !endForm.dataset.submitUrl) return;
    const submit = endForm.querySelector('[type="submit"]');
    const csrf = document.querySelector('#mentorship-csrf-token [name="csrfmiddlewaretoken"]')?.value || '';
    submit.disabled = true;
    endError.hidden = true;
    try {
      const response = await fetch(endForm.dataset.submitUrl, {
        method: 'POST', credentials:'same-origin',
        headers: {'X-CSRFToken': csrf, 'Accept':'application/json'},
        body: new FormData(endForm)
      });
      const contentType = response.headers.get('content-type') || '';
      const payload = contentType.includes('json') ? await response.json() : {};
      if (!response.ok || !payload.success) throw new Error(payload.error || 'Unable to end this mentorship. Please refresh and try again.');
      window.location.reload();
    } catch (error) {
      endError.textContent = error.message;
      endError.hidden = false;
      submit.disabled = false;
    }
  });
})();
