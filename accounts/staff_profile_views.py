"""Administrative account identity, separate from verified alumni identity.

Admin permissions and Alumni records are independent attributes of the same user.
No alumni record is generated by viewing/editing a staff account.
"""
from django.contrib import messages
from django.contrib.auth import update_session_auth_hash
from django.db import DatabaseError
import logging
from django.views.decorators.cache import never_cache
from django.views.decorators.http import require_http_methods
from django_ratelimit.decorators import ratelimit

from .security import SecurityAuditLogger
from .staff_account_forms import StaffPasswordChangeForm, StaffEmailChangeForm
from .staff_email_change import (
    EmailAlreadyTaken, InvalidEmailChangeToken, confirm_email_change,
    send_email_change_link, validate_email_change_token,
)
from django.contrib.auth.decorators import login_required
from django.http import Http404, HttpResponseForbidden
from django.shortcuts import redirect, render

from jobs.hr_access import is_hr_only
from alumni_directory.models import Alumni
from .forms import UserUpdateForm

logger = logging.getLogger(__name__)


def has_staff_workspace(user):
    if not user.is_authenticated:
        return False
    if user.is_superuser or user.is_staff:
        return True
    profile = getattr(user, 'profile', None)
    return bool(profile and (profile.is_alumni_coordinator or is_hr_only(user)))


def has_verified_alumni(user):
    """Verified graduation is explicit; a generic Profile is not proof."""
    return bool(user.is_authenticated and Alumni.objects.filter(user_id=user.pk, is_verified=True).exists())


def _require_staff(user):
    if not has_staff_workspace(user):
        return HttpResponseForbidden('This page is for administrative accounts.')
    return None


def _staff_profile_context(user, *, form=None):
    profile = getattr(user, 'profile', None)
    roles = []
    if user.is_superuser:
        roles.append('System Administrator')
    elif user.is_staff:
        roles.append('Staff')
    if profile and profile.is_alumni_coordinator:
        roles.append('Alumni Coordinator')
    if profile and profile.is_hr:
        roles.append('HR')
    return {
        'account': user,
        'staff_roles': roles or ['Administration'],
        'has_alumni_identity': has_verified_alumni(user),
        'form': form,
    }


@login_required
def staff_profile(request):
    denial = _require_staff(request.user)
    if denial:
        return denial
    return render(request, 'accounts/staff_profile.html',
                  _staff_profile_context(request.user))


@login_required
def edit_staff_profile(request):
    denial = _require_staff(request.user)
    if denial:
        return denial
    form = UserUpdateForm(request.POST or None, instance=request.user)
    if request.method == 'POST' and form.is_valid():
        form.save()
        messages.success(request, 'Account name updated.')
        return redirect('accounts:staff_profile')
    return render(request, 'accounts/staff_profile.html',
                  _staff_profile_context(request.user, form=form))


@login_required
def my_alumni_profile(request):
    if not has_verified_alumni(request.user):
        raise Http404('A verified alumni record is not linked to this account.')
    from .views import profile_detail
    return profile_detail(request, username=request.user.username)


@login_required
@ratelimit(key='user', rate='5/15m', method='POST', block=True)
@require_http_methods(['GET', 'POST'])
def change_staff_password(request):
    denial = _require_staff(request.user)
    if denial:
        return denial
    form = StaffPasswordChangeForm(request.user, request.POST or None)
    if request.method == 'POST' and form.is_valid():
        user = form.save()
        update_session_auth_hash(request, user)
        SecurityAuditLogger.log_event('staff_password_change_success', user=user,
                                      ip_address=request.META.get('REMOTE_ADDR'))
        messages.success(request, 'Your password has been changed.')
        return redirect('accounts:staff_profile')
    return render(request, 'accounts/staff_account_security_form.html', {
        'form': form, 'page_title': 'Change Password', 'button_label': 'Update password',
        'description': 'Enter your current password before choosing a new password.',
    })


@login_required
@ratelimit(key='user', rate='5/15m', method='POST', block=True)
@require_http_methods(['GET', 'POST'])
def change_staff_email(request):
    denial = _require_staff(request.user)
    if denial:
        return denial
    form = StaffEmailChangeForm(request.POST or None, user=request.user)
    if request.method == 'POST' and form.is_valid():
        try:
            send_email_change_link(request, request.user, form.cleaned_data['new_email'])
        except Exception:
            # Do not change User.email, EmailAddress, or ContactInfo on send failure.
            logger.exception('Staff email verification request could not be sent')
            form.add_error(None, 'The verification message could not be sent. Please try again later.')
        else:
            SecurityAuditLogger.log_event('staff_email_change_requested', user=request.user,
                                          ip_address=request.META.get('REMOTE_ADDR'))
            messages.success(
                request, 'We sent a confirmation link to your proposed email address. '
                'Your current email will remain active until you confirm.'
            )
            return redirect('accounts:staff_profile')
    return render(request, 'accounts/staff_account_security_form.html', {
        'form': form, 'page_title': 'Change Email', 'button_label': 'Send verification link',
        'description': 'Confirm your current password. A link valid for 30 minutes will be sent to the new address.',
    })


@login_required
@never_cache
@ratelimit(key='user', rate='5/15m', method='POST', block=True)
@require_http_methods(['GET', 'POST'])
def confirm_staff_email(request, token):
    denial = _require_staff(request.user)
    if denial:
        return denial
    try:
        new_email = validate_email_change_token(request.user, token)
    except InvalidEmailChangeToken:
        return render(request, 'accounts/staff_confirm_email.html',
                      {'error': 'This verification link is invalid, expired, or already used.'}, status=400)
    if request.method == 'POST':
        try:
            confirmed_email = confirm_email_change(request.user, token)
        except (InvalidEmailChangeToken, EmailAlreadyTaken) as exc:
            return render(request, 'accounts/staff_confirm_email.html',
                          {'error': str(exc)}, status=400)
        except DatabaseError:
            return render(request, 'accounts/staff_confirm_email.html',
                          {'error': 'The account update could not be completed. Please retry.'}, status=500)
        request.user.email = confirmed_email
        SecurityAuditLogger.log_event('staff_email_change_success', user=request.user,
                                      ip_address=request.META.get('REMOTE_ADDR'))
        messages.success(request, 'Your email address has been verified and updated.')
        return redirect('accounts:staff_profile')
    return render(request, 'accounts/staff_confirm_email.html', {'new_email': new_email})


@login_required
@require_http_methods(['GET', 'POST'])
def account_email_management_gateway(request):
    """Stop staff from using allauth /accounts/email/ to bypass password verification."""
    if has_staff_workspace(request.user):
        if request.method == 'POST':
            return HttpResponseForbidden('Use the verified staff email-change workflow.')
        return redirect('accounts:change_staff_email')
    # Preserve the existing allauth email management for normal alumni accounts.
    from allauth.account.views import email as allauth_email
    return allauth_email(request)
