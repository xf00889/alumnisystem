"""Build the ordered anonymous-homepage CSS bundle.

Run `python scripts/build_public_home_css.py` after editing the component CSS,
and commit the regenerated bundle together with the source styles.

No third-party build tools and no Django/database dependency.
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
STYLES = (
    "css/footer.css",
    "css/public_tracer_studies.css",
    "css/toast-notifications.css",
    "css/modules/layout-public.css",
    "css/university_header.css",
    "css/home_redesign.css",
    "css/public_redesign.css",
    "css/landing-performance.css",
    "css/public_typography.css",
    "css/home_experience.css",
)
OUTPUT = ROOT / "static" / "css" / "public-home-bundle.css"


def build() -> str:
    parts = ["/* Generated by scripts/build_public_home_css.py. Do not hand-edit. */\n"]
    for relative_path in STYLES:
        path = ROOT / "static" / relative_path
        css = path.read_text(encoding="utf-8")
        # Relative urls are resolved from the combined file's directory.
        # All references here use the static/css root, except the nested
        # layout-public file, which currently contains no relative urls.
        if relative_path.startswith("css/modules/") and "url(" in css:
            raise ValueError(f"Nested stylesheet may need URL rebasing: {relative_path}")
        parts.append(f"\n/* Source: {relative_path} */\n{css}\n")
    return "".join(parts)


def main() -> None:
    content = build()
    OUTPUT.write_text(content, encoding="utf-8")
    digest = hashlib.sha256(content.encode("utf-8")).hexdigest()[:12]
    print(f"Built {OUTPUT.relative_to(ROOT)} ({len(content):,} chars; SHA256 {digest})")


if __name__ == "__main__":
    main()
